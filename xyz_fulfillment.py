"""Inventory in Main vs Backup Warehouse:"""

inventory_chart = inventory[
    ["Product", "Main Warehouse", "Backup Warehouse"]
]

inventory_long = inventory_chart.melt(
    id_vars="Product",
    var_name="Warehouse",
    value_name="Stock"
)

fig = px.bar(
    inventory_long,
    x="Product",
    y="Stock",
    color="Warehouse",
    barmode="group",
    title="Inventory by Warehouse"
)

fig.update_layout(
    xaxis_title="Product",
    yaxis_title="Stock Quantity"
)

fig.show()

"""Low Stock Products:"""

inventory["Stock Status"] = inventory.apply(
    lambda row: "Low Stock"
    if row["Main Warehouse"] <= row["Minimum Stock"]
    else "Healthy",
    axis=1
)

inventory_status = inventory[
    ["Product", "Main Warehouse", "Minimum Stock", "Stock Status"]
]

inventory_status

fig = px.bar(
    inventory_status,
    x="Product",
    y=["Main Warehouse", "Minimum Stock"],
    barmode="group",
    title="Current Stock vs Minimum Stock"
)

fig.update_layout(
    xaxis_title="Product",
    yaxis_title="Quantity"
)

fig.show()

""" Orders Requiring Attention:"""

issues = orders[
    (orders["Priority"] == "Yes") |
    (orders["Status"] == "Inventory Issue") |
    (orders["Status"] == "Picking")
]

issues

issue_count = issues["Status"].value_counts().reset_index()

issue_count.columns = ["Issue", "Orders"]

fig = px.bar(
    issue_count,
    x="Issue",
    y="Orders",
    color="Issue",
    title="Orders Requiring Attention",
    text="Orders"
)

fig.update_layout(
    xaxis_title="Issue / Status",
    yaxis_title="Number of Orders",
    showlegend=False
)

fig.show()

