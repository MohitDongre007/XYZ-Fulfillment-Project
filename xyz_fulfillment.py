"""Delevloping required KPI's:"""

total_orders = len(orders)

priority_orders = len(
    orders[orders["Priority"] == "Yes"]
)

inventory_issues = len(
    orders[orders["Status"] == "Inventory Issue"]
)

at_risk_orders = len(
    orders[
        orders["Status"].isin(
            ["Processing", "Picking"]
        )
    ]
)

print("Total Orders:", total_orders)
print("Priority Orders:", priority_orders)
print("Inventory Issues:", inventory_issues)
print("At Risk Orders:", at_risk_orders)

"""Now the Visualization comes into role:

Orders by Status:
"""

import plotly.express as px

status_count = orders["Status"].value_counts().reset_index()

status_count.columns = ["Status", "Orders"]

fig = px.bar(
    status_count,
    x="Status",
    y="Orders",
    color="Status",
    title="Orders by Fulfillment Status",
    text="Orders"
)

fig.update_layout(
    xaxis_title="Order Status",
    yaxis_title="Number of Orders",
    showlegend=False
)

fig.show()

"""Priority vs Normal Orders:

"""

priority_count = orders["Priority"].value_counts().reset_index()

priority_count.columns = ["Priority", "Orders"]

fig = px.pie(
    priority_count,
    names="Priority",
    values="Orders",
    title="Priority vs Normal Orders"
)

fig.show()

"""Orders by Channel:"""

channel_count = orders["Channel"].value_counts().reset_index()

